#!/usr/bin/env python3
"""Generate recording-level descriptive statistics for UCI Parkinsons dataset 174."""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from scipy.stats import mannwhitneyu
from sklearn.metrics import roc_auc_score
from ucimlrepo import fetch_ucirepo

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "VALIDATION.md"
FEATURES = {
    "Jitter (%)": ("mdvp:jitter", 100.0),
    "Shimmer (%)": ("mdvp:shimmer", 100.0),
    "HNR (dB)": ("hnr", 1.0),
}


def find_feature(columns, key: str) -> int:
    lowered = [str(column).strip().casefold() for column in columns]
    matches = [index for index, column in enumerate(lowered) if column == key]
    if matches:
        # UCI returns duplicate base labels for some unit variants; the first
        # MDVP:Jitter/Shimmer columns are the percent/base feature versions.
        return matches[0]
    raise KeyError(f"UCI dataset feature not found: {key}; available: {list(columns)}")


def mean_sd(values) -> str:
    values = np.asarray(values, dtype=float)
    return f"{values.mean():.4f} ± {values.std(ddof=1):.4f}"


def main() -> None:
    dataset = fetch_ucirepo(id=174)
    features = dataset.data.features
    targets = dataset.data.targets
    target_name = next((column for column in targets.columns if str(column).casefold() == "status"), None)
    if target_name is None:
        raise KeyError(f"UCI target 'status' not found; available: {list(targets.columns)}")

    status = targets[target_name].astype(int).to_numpy()
    if set(np.unique(status)) != {0, 1}:
        raise ValueError(f"Expected UCI status labels 0/1, received {sorted(set(status))}")
    rows = []
    for label, (feature_key, scale) in FEATURES.items():
        column_index = find_feature(features.columns, feature_key)
        # UCI exposes jitter/shimmer as ratios (0.01 = 1%); report in percent.
        values = features.iloc[:, column_index].astype(float).to_numpy() * scale
        control = values[status == 0]
        pd_group = values[status == 1]
        test = mannwhitneyu(pd_group, control, alternative="two-sided", method="auto")
        auc = roc_auc_score(status, values)
        rows.append(
            f"| {label} | {len(control)} | {mean_sd(control)} | {len(pd_group)} | "
            f"{mean_sd(pd_group)} | {test.statistic:.2f} | {test.pvalue:.6g} | {auc:.4f} |"
        )

    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    markdown = f"""# Validation

Generated by `python scripts/validate_uci_voice.py` on {generated}.

## UCI Parkinsons voice dataset (recording-level comparison)

Source: [UCI Machine Learning Repository, Parkinsons dataset 174](https://archive.ics.uci.edu/dataset/174/parkinsons). The source describes 195 recordings from 31 people (23 with Parkinson's disease); rows from the same person are repeated and are **not independent participants**. The table below reports group means ± sample SD, two-sided Mann–Whitney U p-values, and raw single-feature AUROC with UCI `status=1` as the positive label. No classifier is trained. AUROC summarizes how one dataset feature ranks these rows; it is not an individual probability, and repeated recordings mean this is not a participant-held-out validation result.

UCI's jitter and shimmer columns are stored as ratios; this script multiplies them by 100 for the displayed percent units. HNR is reported in its source dB units. AUROC is unchanged by the jitter/shimmer unit conversion.

| Feature | Control recordings | Control mean ± SD | PD recordings | PD mean ± SD | Mann–Whitney U | p-value | AUROC (PD=1) |
|---|---:|---:|---:|---:|---:|---:|---:|
{chr(10).join(rows)}

## What this does and does not validate

- The script makes the UCI feature-level comparison reproducible and documents the dataset's reported recording/participant counts.
- UCI's recorded acoustic features are not outputs from NeuroMotion's browser algorithm. Its jitter/shimmer/HNR definitions, microphone, task, and preprocessing may differ; these numbers do **not** validate the browser estimator, its provisional bands, webcam tremor/tapping measures, or a clinical screening decision.
- The browser tests use synthetic signals with known inputs. They verify math behavior on those signals only, not performance on real people, consumer devices, or a clinical cohort.
- Consumer microphone and webcam variation, language, age, sex, posture, environment, missing-hand frames, and repeated measures require separate prospective validation before thresholds could be treated as reference limits.

## Synthetic engine tests

Run `cd frontend && npm test`. Tests assert recovery of a synthetic 5 Hz displacement, repeated tapping with amplitude decrement, a sustained synthetic vowel with measurable jitter/shimmer/HNR and voiced fraction, and quality-gate exclusion. Passing these tests means the implementation responds to the specified generated signals; it does not establish real-world measurement accuracy or clinical validity.

## Threshold status

Every in-app comparison band is centralized in `frontend/src/features/analysis/screeningTriage.js` and marked `provisional` with source `to verify`. These custom bands are not calibrated on the UCI data or consumer hardware and must not be interpreted as disease reference limits. The app reports modality-level flags and quality; it does not calculate an ML output, probability, or 0–100 risk score.
"""
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(markdown, encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
